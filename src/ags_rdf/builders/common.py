"""Shared helpers for the RDF builders."""

from __future__ import annotations

from dataclasses import dataclass, field

from rdflib import DCTERMS, OWL, PROV, RDF, RDFS, SDO, SKOS, XSD, Graph, Literal, Namespace, URIRef

from .. import __version__
from ..config import Agent, Settings
from ..iris import IRIs
from ..model import Dictionary
from ..namespaces import PREFIXES, REG
from ..sources import Snapshot


@dataclass
class BuildContext:
    dictionary: Dictionary
    snapshot: Snapshot
    settings: Settings = field(default_factory=Settings)
    iris: IRIs | None = None

    def __post_init__(self):
        if self.iris is None:
            self.iris = IRIs(self.settings.base_iri)

    @property
    def version(self) -> str:
        return self.dictionary.version

    # ---------------------------------------------------------------- graph
    def new_graph(self, extra_prefixes: dict[str, str] | None = None) -> Graph:
        g = Graph(bind_namespaces="none")
        for p, ns in PREFIXES.items():
            g.bind(p, Namespace(ns))
        g.bind("agso", self.iris.AGSO)
        g.bind("ags", self.iris.AGS)
        g.bind("agssh", self.iris.SH)
        for p, ns in (extra_prefixes or {}).items():
            g.bind(p, Namespace(ns))
        return g

    def text(self, value: str) -> Literal:
        return Literal(value, lang=self.settings.language)

    # ---------------------------------------------------------- provenance
    def add_agent(self, g: Graph, agent: Agent) -> URIRef:
        iri = URIRef(agent.iri)
        g.add((iri, RDF.type, SDO.Organization))
        g.set((iri, SDO.name, Literal(agent.name)))
        g.set((iri, SDO.url, Literal(agent.url, datatype=XSD.anyURI)))
        return iri

    def source_url(self, rel: str) -> URIRef:
        return URIRef(self.snapshot.url_for(rel))

    def history_note(self, files: list[str]) -> str:
        s = self.snapshot
        where = f"{s.project_url}"
        if s.commit:
            where += f" at commit {s.commit[:12]}"
        if s.committed_date:
            where += f" ({s.committed_date[:10]})"
        return (f"Generated by ags-rdf {__version__} from the AGS {self.version} data dictionary JSON "
                f"({', '.join(files)}) published in {where}. The JSON files are treated as the "
                "authoritative source; values are only cleaned of formatting artefacts.")

    def describe_document(self, g: Graph, iri: URIRef, kind: URIRef, title: str, description: str,
                          files: list[str], status: URIRef | None = None) -> None:
        """Metadata required by VocPub for a ConceptScheme (also used for ontologies/shapes)."""
        rel = self.dictionary.release
        created, modified = self.snapshot.dates_for(files)
        g.add((iri, RDF.type, kind))
        g.add((iri, SKOS.prefLabel if kind == SKOS.ConceptScheme else RDFS.label, self.text(title)))
        g.add((iri, SKOS.definition if kind == SKOS.ConceptScheme else RDFS.comment, self.text(description)))
        if kind != SKOS.ConceptScheme:
            g.add((iri, SDO.name, self.text(title)))
            g.add((iri, SDO.description, self.text(description)))
        g.add((iri, SDO.dateCreated, Literal(created, datatype=XSD.date)))
        g.add((iri, SDO.dateModified, Literal(modified, datatype=XSD.date)))
        g.add((iri, SDO.creator, self.add_agent(g, self.settings.creator)))
        g.add((iri, SDO.publisher, self.add_agent(g, self.settings.publisher)))
        g.add((iri, SDO.copyrightHolder, self.add_agent(g, self.settings.rights_holder)))
        g.add((iri, DCTERMS.rights, Literal(
            f"Content of the AGS Data Format data dictionary (AGS {rel.version}), "
            f"© {self.settings.rights_holder.name}. Reuse is subject to the AGS's terms; see "
            "https://www.ags.org.uk/data-format/. No licence is stated in the source repository.")))
        g.add((iri, SDO.version, Literal(rel.version)))
        g.add((iri, OWL.versionIRI, self.iris.version_iri(iri, rel.version)))
        g.add((iri, OWL.versionInfo, Literal(rel.version)))
        if rel.published:
            g.add((iri, SDO.datePublished, Literal(rel.published, datatype=XSD.gYearMonth)))
        g.add((iri, SKOS.historyNote, Literal(self.history_note(files))))
        g.add((iri, SDO.citation, Literal("https://www.ags.org.uk/data-format/", datatype=XSD.anyURI)))
        for f in files:
            g.add((iri, PROV.wasDerivedFrom, self.source_url(f)))
        if status is not None:
            g.add((iri, SDO.status, status))
            g.add((iri, REG.status, status))
